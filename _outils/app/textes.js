function langue() {
  const hote = global.studiesHote;
  const l = hote && typeof hote.langue === 'function' ? hote.langue() : 'fr';
  return TEXTES[l] ? l : 'fr';
}

function t(cle, vars) {
  const texte = TEXTES[langue()][cle] ?? TEXTES.fr[cle] ?? cle;
  return vars ? texte.replace(/\{(\w+)\}/g, (m, k) => (vars[k] === undefined ? m : String(vars[k]))) : texte;
}

module.exports = { t, langue, TEXTES };
